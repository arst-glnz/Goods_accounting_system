package com.example.triggerdemo.service;

import java.util.Locale;
import org.springframework.stereotype.Service;

@Service
public class FaqService {
    private static final String UNKNOWN_ANSWER = "Я пока не знаю ответа на этот вопрос. "
            + "Попробуйте спросить про добавление, изменение или удаление товара, аудит, "
            + "варианты, складские операции, заказы, остатки или роли.";

    public String answer(String question) {
        String normalized = question.toLowerCase(Locale.ROOT).replace('ё', 'е');

        if (containsAny(normalized, "кто может удалить", "кто удаляет", "кто имеет право удалить")) {
            return "Удалять товары может только пользователь с ролью ADMIN. "
                    + "У MANAGER такой возможности нет.";
        }
        if (containsAny(normalized, "как добавить", "добавить товар", "создать товар")) {
            return "Войдите в систему и нажмите «Добавить товар». Укажите название и цену, "
                    + "а затем добавьте варианты и начальный приход на странице «Склад».";
        }
        if (containsAny(normalized, "как изменить", "изменить товар", "редактировать товар")) {
            return "В списке товаров нажмите «Изменить» рядом с нужным товаром, "
                    + "обновите поля и сохраните изменения.";
        }
        if (containsAny(normalized, "как удалить", "удалить товар", "удаление товара")) {
            return "Пользователь ADMIN может удалить товар кнопкой «Удалить» в списке. "
                    + "Перед удалением система попросит подтверждение.";
        }
        if (containsAny(normalized, "аудит", "изменение цены")) {
            return "Аудит — это журнал изменения цен. Записи автоматически добавляет "
                    + "триггер PostgreSQL; журнал доступен ADMIN по ссылке «Аудит».";
        }
        if (containsAny(normalized, "журнал", "истори")) {
            return "ADMIN может открыть «Аудит» для истории изменения цен и "
                    + "«Создания» для записей о добавленных товарах.";
        }
        if (containsAny(normalized, "мало товара", "низкий остаток", "мало остатка",
                "мало на складе")) {
            return "Статус «Мало» означает остаток от 1 до 5 единиц. Проверьте страницу "
                    + "аналитики или отфильтруйте такие товары в списке.";
        }
        if (containsAny(normalized, "вариант", "размер товара", "размеры товара")) {
            return "Откройте «Варианты» в строке товара. Там можно добавить или изменить "
                    + "размер и характеристики; количество меняется отдельно на странице «Склад».";
        }
        if (containsAny(normalized, "приход", "поступление товара", "пополнить остаток")) {
            return "Откройте страницу «Склад», выберите вариант, склад, операцию «Приход» "
                    + "и количество. Система запишет операцию в историю остатков.";
        }
        if (containsAny(normalized, "списание", "списать товар", "уменьшить остаток")) {
            return "На странице «Склад» выберите вариант и операцию «Списание». Нельзя "
                    + "списать больше единиц, чем есть в наличии.";
        }
        if (containsAny(normalized, "остаток", "склад", "движени")) {
            return "Текущий остаток складывается из количества по вариантам. На странице "
                    + "«Склад» доступны остатки и история приходов/списаний.";
        }
        if (containsAny(normalized, "как создать заказ", "создать заказ", "оформить заказ")) {
            return "Откройте «Заказы» → «Создать заказ», заполните получателя и добавьте "
                    + "одну или несколько позиций. Новый заказ не списывает остаток.";
        }
        if (containsAny(normalized, "подтвердить заказ", "подтверждение заказа",
                "подтверждении заказа")) {
            return "При подтверждении заказа система проверит наличие всех позиций и "
                    + "спишет остатки одной операцией. При нехватке весь заказ останется новым.";
        }
        if (containsAny(normalized, "отменить заказ", "отмена заказа")) {
            return "Новый заказ можно отменить без изменения остатков. При отмене заказа "
                    + "в обработке ранее списанные единицы возвращаются на склад.";
        }
        if (containsAny(normalized, "статус заказа", "статусы заказа", "завершить заказ")) {
            return "Статусы заказа: NEW (остаток не списан), PROCESSING (подтверждён и "
                    + "списан), COMPLETED или CANCELLED.";
        }
        if (containsAny(normalized, "роль", "роли", "manager", "admin")) {
            return "ADMIN и MANAGER могут вести товары, варианты, остатки и заказы. "
                    + "Только ADMIN может удалять неиспользуемые товары, просматривать журналы и аналитику.";
        }
        return UNKNOWN_ANSWER;
    }

    private boolean containsAny(String text, String... terms) {
        for (String term : terms) {
            if (text.contains(term)) {
                return true;
            }
        }
        return false;
    }
}
